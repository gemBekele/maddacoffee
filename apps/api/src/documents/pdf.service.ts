// ── helpers ────────────────────────────────────────────────────────────

function slug(s: string) {
  return s
    .toLowerCase()
    .replace(/[^a-z0-9]+/g, '-')
    .replace(/^-|-$/g, '');
}

const ONES = [
  '', 'one', 'two', 'three', 'four', 'five', 'six', 'seven', 'eight', 'nine', 'ten',
  'eleven', 'twelve', 'thirteen', 'fourteen', 'fifteen', 'sixteen', 'seventeen', 'eighteen', 'nineteen',
];
const TENS = ['', '', 'twenty', 'thirty', 'forty', 'fifty', 'sixty', 'seventy', 'eighty', 'ninety'];

function below1000(n: number): string {
  if (n === 0) return '';
  if (n < 20) return ONES[n];
  if (n < 100) return `${TENS[Math.floor(n / 10)]}${n % 10 ? `-${ONES[n % 10]}` : ''}`;
  return `${ONES[Math.floor(n / 100)]} hundred${n % 100 ? ` and ${below1000(n % 100)}` : ''}`;
}

/** Amount in words, the form most banks and customs still expect on an invoice. */
export function amountInWords(amount: number, currency = 'USD'): string {
  const names: Record<string, string> = { USD: 'US dollars', EUR: 'euro', GBP: 'pounds sterling', ETB: 'birr' };
  const unit = names[currency] ?? currency;
  const whole = Math.floor(Math.abs(amount));
  const cents = Math.round((Math.abs(amount) - whole) * 100);

  if (whole === 0 && cents === 0) return `Zero ${unit} only.`;

  const scale: [number, string][] = [
    [1_000_000_000, 'billion'],
    [1_000_000, 'million'],
    [1_000, 'thousand'],
  ];
  let rest = whole;
  const parts: string[] = [];
  for (const [value, label] of scale) {
    const count = Math.floor(rest / value);
    if (count) {
      parts.push(`${below1000(count)} ${label}`);
      rest %= value;
    }
  }
  if (rest) parts.push(below1000(rest));

  const words = parts.join(' ').replace(/\s+/g, ' ').trim();
  const centsPart = cents ? ` and ${below1000(cents)} cents` : '';
  const capitalised = words.charAt(0).toUpperCase() + words.slice(1);
  return `${capitalised} ${unit}${centsPart} only.`;
}
