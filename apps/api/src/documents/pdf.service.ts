  // ── dispatcher ───────────────────────────────────────────────────────

  /**
   * Render the PDF for a given document type on an invoice.
   *
   * Types not explicitly handled fall through to a control sheet, so every
   * document in the pack has a printable artefact.
   */
  async renderForInvoice(invoiceId: string, docType: string): Promise<RenderedDocument> {
    switch (docType) {
      case 'Commercial Invoice':
        return this.commercialInvoice(invoiceId);
      case 'Packing List':
        return this.packingList(invoiceId);
      case 'CLU Quality Certificate':
        return this.qualityData(invoiceId);
      case 'ICO Certificate of Origin':
        return this.icoData(invoiceId);
      case 'Phytosanitary Certificate':
        return this.phytosanitaryData(invoiceId);
      case 'EUDR Plot Geolocation Dossier':
      case 'EUDR Due Diligence Statement':
        return this.eudrDossier(invoiceId);
      default: {
        if (AUTHORITY_ISSUED.has(docType)) return this.controlSheet(invoiceId, docType);
        return this.controlSheet(invoiceId, docType);
      }
    }
  }

  /**
   * Every PDF that should accompany a consignment.
   *
   * Scoped to documents that are actually applicable (not retracted) and to the
   * ones we can produce, so an email does not carry a pile of control sheets for
   * irrelevant rows.
   */
  async packForInvoice(invoiceId: string): Promise<RenderedDocument[]> {
    const invoice = await this.loadInvoice(invoiceId);
    const applicable = invoice.documents.filter((d) => d.status !== 'NotApplicable');

    const produce = new Set([
      'Commercial Invoice',
      'Packing List',
      'CLU Quality Certificate',
      'ICO Certificate of Origin',
      'Phytosanitary Certificate',
      'EUDR Plot Geolocation Dossier',
      'EUDR Due Diligence Statement',
    ]);

    const wanted = applicable.filter((d) => produce.has(d.docType));
    const out: RenderedDocument[] = [];
    for (const doc of wanted) {
      try {
        out.push(await this.renderForInvoice(invoiceId, doc.docType));
      } catch (e) {
        // One failed renderer must not stop the email; the rest of the pack
        // still goes out and the failure is visible in the log.
        this.logger.error(`Failed to render ${doc.docType} for invoice ${invoice.code}: ${(e as Error).message}`);
      }
    }
    return out;
  }
