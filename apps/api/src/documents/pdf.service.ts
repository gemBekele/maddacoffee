  // ── EUDR dossier ─────────────────────────────────────────────────────

  async eudrDossier(invoiceId: string): Promise<RenderedDocument> {
    const invoice = await this.loadInvoice(invoiceId);
    const company = await this.company();
    const lines = this.invoiceLines(invoice);
    const lotIds = [...new Set(lines.map((l: any) => l.lotId).filter(Boolean))] as string[];

    const traces = lotIds.length
      ? await this.prisma.lotTrace.findMany({
          where: { lotId: { in: lotIds } },
          include: { plot: { include: { producer: true } } },
        })
      : [];

    const byPlot = new Map<string, any>();
    for (const t of traces) {
      const cur = byPlot.get(t.plotId) ?? { plot: t.plot, lots: new Set<string>(), kg: 0 };
      cur.lots.add(t.lotId);
      cur.kg += Number(t.contributedKg ?? 0);
      byPlot.set(t.plotId, cur);
    }
    const plots = [...byPlot.values()];

    const b = new DocumentBuilder(
      { title: 'EUDR Due Diligence — Geolocation Dossier', reference: invoice.code, company },
      this.footer(company),
    );

    b.note(
      'This dossier supplies the production plot data the EU importer needs in order to file a Due Diligence Statement under Regulation (EU) 2023/1115. ' +
        'The statement itself is submitted by the EU importer or operator in the EUDR Information System. Neither the exporter nor this document constitutes a filed statement.',
      'info',
    );
    b.space(4);

    b.keyValues(
      [
        { label: 'Consignment', value: invoice.code },
        { label: 'Commodity', value: 'Coffee' },
        { label: 'HS code', value: invoice.hsCode },
        { label: 'Country of production', value: 'Ethiopia' },
        { label: 'Destination', value: invoice.destinationCountryName ?? invoice.buyer?.country },
        { label: 'Plots declared', value: String(plots.length) },
        { label: 'Geolocated plots', value: String(plots.filter((p) => p.plot.polygon).length) },
        { label: 'Production period', value: [...new Set(lines.map((l: any) => l.lotId))].length ? 'see harvest year per lot' : '—' },
      ],
      2,
    );

    b.space(4);
    b.sectionTitle('Plots contributing to this consignment');
    b.table({
      columns: [
        { header: 'Plot', width: 0.16, render: (r) => r.plot.id.slice(0, 10) },
        { header: 'Producer', width: 0.2, render: (r) => r.plot.producer?.name ?? '—' },
        { header: 'Type', width: 0.13, render: (r) => r.plot.producer?.kind ?? '—' },
        { header: 'Woreda / Kebele', width: 0.2, render: (r) => [r.plot.woreda, r.plot.kebele].filter(Boolean).join(' / ') || '—' },
        { header: 'Area ha', width: 0.09, align: 'right', render: (r) => (r.plot.areaHa != null ? Number(r.plot.areaHa).toFixed(3) : '—') },
        { header: 'Geodata', width: 0.1, render: (r) => (r.plot.polygon ? (Number(r.plot.areaHa ?? 0) > 4 ? 'Polygon' : 'Point/Polygon') : 'MISSING') },
        { header: 'Lots', width: 0.12, render: (r) => [...r.lots].join(', ') },
      ],
      rows: plots,
      emptyText: 'No production plots are linked to the lots on this invoice.',
    });

    const missing = plots.filter((p) => !p.plot.polygon);
    if (!plots.length || missing.length) {
      b.note(
        !plots.length
          ? 'This consignment cannot be supported for EUDR. No plot data is linked to the lots, and a Due Diligence Statement cannot be filed without the geolocation of every contributing plot. Link the contributing farms to the lots before shipment.'
          : `${missing.length} plot(s) have no geolocation recorded. EUDR requires six-decimal coordinates — a polygon for plots over 4 hectares, and at least a single point below that. The importer cannot file a compliant statement until these are supplied.`,
        'warn',
      );
    }

    b.space(4);
    b.sectionTitle('Machine-readable geolocation');
    const collection = {
      type: 'FeatureCollection',
      features: plots
        .filter((p) => p.plot.polygon)
        .map((p) => ({
          type: 'Feature',
          geometry: p.plot.polygon,
          properties: {
            plotId: p.plot.id,
            producer: p.plot.producer?.name,
            producerKind: p.plot.producer?.kind,
            woreda: p.plot.woreda,
            kebele: p.plot.kebele,
            areaHa: p.plot.areaHa ? Number(p.plot.areaHa) : null,
            lots: [...p.lots],
          },
        })),
    };
    b.paragraph(
      'The GeoJSON FeatureCollection for this consignment is available from the API at ' +
        `GET /api/traceability/eudr/{shipmentId}/geojson and can be supplied to the importer as a file. ` +
        `This consignment declares ${collection.features.length} geolocated plot(s).`,
      { size: 8.5, colour: COLOURS.muted },
    );

    return {
      docType: 'EUDR Plot Geolocation Dossier',
      filename: `${invoice.code}-eudr-geolocation-dossier.pdf`,
      buffer: await b.toBuffer(),
      isPrimaryDocument: true,
    };
  }

